using System;
using System.Collections;
using UnityEngine;
using UnityEngine.UI;
using TMPro;

namespace MonsterSurvival.Menu6B1
{
    /// <summary>
    /// Stage 6B.1: menu VISUAL overlay. Routes button clicks to existing menu button
    /// listeners, never replaces MainMenuController, AudioManager or scene navigation.
    /// </summary>
    [DisallowMultipleComponent]
    public sealed class MM6B1View : MonoBehaviour
    {
        [Header("V2 UI generated by installer")]
        public CanvasGroup overlay;
        public Button playButton;
        public Button mapsButton;
        public Button settingsButton;
        public Button quitButton;
        public TMP_Text statusText;

        [Header("Existing menu buttons - assign if auto detection misses")]
        public Button oldPlayButton;
        public Button oldMapsButton;
        public Button oldSettingsButton;
        public Button oldQuitButton;

        [Header("Existing panels - do not move/reparent")]
        public GameObject oldSettingsPanel;
        public GameObject oldMapsPanel;

        [Header("Subtle animation")]
        [Range(0.05f, 1.5f)] public float fadeDuration = 0.35f;

        bool busy;
        Coroutine waiter;

        void Awake()
        {
            if (playButton != null) playButton.onClick.AddListener(Play);
            if (mapsButton != null) mapsButton.onClick.AddListener(OpenMaps);
            if (settingsButton != null) settingsButton.onClick.AddListener(OpenSettings);
            if (quitButton != null) quitButton.onClick.AddListener(Quit);
        }

        IEnumerator Start()
        {
            if (overlay == null) yield break;
            overlay.alpha = 0f;
            overlay.interactable = false;
            overlay.blocksRaycasts = false;
            float elapsed = 0f;
            while (elapsed < fadeDuration)
            {
                elapsed += Time.unscaledDeltaTime;
                overlay.alpha = Mathf.Clamp01(elapsed / Mathf.Max(0.05f, fadeDuration));
                yield return null;
            }
            overlay.alpha = 1f;
            overlay.interactable = true;
            overlay.blocksRaycasts = true;
            SetMessage(string.Empty);
        }

        public void Play()
        {
            if (busy) return;
            if (oldPlayButton == null)
            {
                SetMessage("CONNECT OLD PLAY BUTTON IN INSPECTOR");
                Debug.LogWarning("[6B.1] Assign oldPlayButton (existing MainMenu Play) to preserve original scene routing.", this);
                return;
            }
            StartCoroutine(FadeThen(() => oldPlayButton.onClick.Invoke()));
        }

        public void OpenSettings()
        {
            if (busy) return;
            if (oldSettingsButton == null && oldSettingsPanel == null)
            {
                SetMessage("CONNECT SETTINGS WINDOW IN INSPECTOR");
                return;
            }
            if (oldSettingsButton != null) oldSettingsButton.onClick.Invoke();
            else if (oldSettingsPanel != null) oldSettingsPanel.SetActive(true);
            ShowLegacyPanel(oldSettingsPanel, "SETTINGS OPENED");
        }

        public void OpenMaps()
        {
            if (busy) return;
            if (oldMapsButton == null && oldMapsPanel == null)
            {
                SetMessage("MAP SELECT WILL BE CONNECTED IN STAGE 6B.2");
                return;
            }
            if (oldMapsButton != null) oldMapsButton.onClick.Invoke();
            else if (oldMapsPanel != null) oldMapsPanel.SetActive(true);
            ShowLegacyPanel(oldMapsPanel, "MAP PANEL OPENED");
        }

        void ShowLegacyPanel(GameObject panel, string message)
        {
            if (panel == null || !panel.activeInHierarchy)
            {
                SetMessage(message + " - VERIFY LEGACY PANEL LINK");
                return;
            }
            if (overlay != null)
            {
                overlay.alpha = 0f;
                overlay.interactable = false;
                overlay.blocksRaycasts = false;
            }
            if (waiter != null) StopCoroutine(waiter);
            waiter = StartCoroutine(WaitUntilPanelClosed(panel));
        }

        IEnumerator WaitUntilPanelClosed(GameObject panel)
        {
            while (panel != null && panel.activeInHierarchy)
                yield return null;
            waiter = null;
            if (overlay != null)
            {
                overlay.alpha = 1f;
                overlay.interactable = true;
                overlay.blocksRaycasts = true;
            }
            SetMessage(string.Empty);
        }

        public void Quit()
        {
            if (busy) return;
            StartCoroutine(FadeThen(() =>
            {
                if (oldQuitButton != null) oldQuitButton.onClick.Invoke();
                else
                {
#if UNITY_EDITOR
                    UnityEditor.EditorApplication.isPlaying = false;
#else
                    Application.Quit();
#endif
                }
            }));
        }

        IEnumerator FadeThen(Action action)
        {
            busy = true;
            if (overlay != null)
            {
                overlay.interactable = false;
                overlay.blocksRaycasts = false;
                float start = overlay.alpha;
                float elapsed = 0f;
                while (elapsed < fadeDuration)
                {
                    elapsed += Time.unscaledDeltaTime;
                    overlay.alpha = Mathf.Lerp(start, 0f, Mathf.Clamp01(elapsed / Mathf.Max(0.05f, fadeDuration)));
                    yield return null;
                }
                overlay.alpha = 0f;
            }
            try { action?.Invoke(); }
            catch (Exception ex) { Debug.LogException(ex, this); }
            // If a legacy action did not change scenes, restore controls.
            if (overlay != null)
            {
                overlay.alpha = 1f;
                overlay.interactable = true;
                overlay.blocksRaycasts = true;
            }
            busy = false;
        }

        void SetMessage(string message)
        {
            if (statusText != null) statusText.text = message;
        }

        void OnDestroy()
        {
            if (playButton != null) playButton.onClick.RemoveListener(Play);
            if (mapsButton != null) mapsButton.onClick.RemoveListener(OpenMaps);
            if (settingsButton != null) settingsButton.onClick.RemoveListener(OpenSettings);
            if (quitButton != null) quitButton.onClick.RemoveListener(Quit);
        }
    }
}
