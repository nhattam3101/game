using UnityEngine;

// MonsterSurvival 6A.1: independent visual-only HP bar.
// Reads existing Health events. Never changes Health, AI, damage, wave or victory.
[DisallowMultipleComponent]
public sealed class GW6A1BossHPBarV2 : MonoBehaviour
{
    [Header("Existing gameplay references (read only)")]
    [SerializeField] private Health health;
    [SerializeField] private GraveWardenBossAI graveWardenAI;

    [Header("Bar graphics (generated by installer)")]
    [SerializeField] private Transform barRoot;
    [SerializeField] private SpriteRenderer backplate;
    [SerializeField] private SpriteRenderer damageTrail;
    [SerializeField] private SpriteRenderer hpFill;
    [SerializeField] private SpriteRenderer ornateBorder;
    [SerializeField] private Sprite normalHpSprite;
    [SerializeField] private Sprite phase2HpSprite;

    [Header("Behavior")]
    [Min(0.05f)] public float frontSmoothTime = 0.07f;
    [Min(0f)] public float trailWaitSeconds = 0.18f;
    [Min(0.05f)] public float trailSmoothTime = 0.36f;
    [Min(0f)] public float hurtFlashSeconds = 0.12f;
    [Min(0f)] public float phaseFlashSeconds = 0.35f;
    public bool hideImmediatelyOnDeath = true;

    private float targetRatio = 1f;
    private float frontRatio = 1f;
    private float trailRatio = 1f;
    private float trailResumeTime;
    private float hitFlashRemaining;
    private float phaseFlashRemaining;
    private bool phaseTwoWasActive;

    private void Awake()
    {
        if (health == null) health = GetComponent<Health>();
        if (graveWardenAI == null) graveWardenAI = GetComponent<GraveWardenBossAI>();
    }

    private void OnEnable()
    {
        if (health == null) health = GetComponent<Health>();
        if (health != null)
        {
            health.OnHealthChanged += HandleHealthChanged;
            health.OnDied += HandleDeath;
        }
    }

    private void Start()
    {
        if (health == null)
        {
            Debug.LogWarning("GW6A1 BossHP: Missing Health on Boss root.", this);
            return;
        }
        targetRatio = health.maxHealth <= 0f ? 0f : Mathf.Clamp01(health.CurrentHealth / health.maxHealth);
        frontRatio = targetRatio;
        trailRatio = targetRatio;
        phaseTwoWasActive = IsPhaseTwo();
        UpdateSpritesAndScale();
    }

    private void Update()
    {
        if (health == null) return;
        float dt = Time.deltaTime;
        // Exponential smoothing, independent of FPS.
        frontRatio = SmoothTo(frontRatio, targetRatio, frontSmoothTime, dt);
        if (Time.time >= trailResumeTime)
            trailRatio = SmoothTo(trailRatio, targetRatio, trailSmoothTime, dt);

        bool isPhaseTwo = IsPhaseTwo();
        if (isPhaseTwo && !phaseTwoWasActive)
            phaseFlashRemaining = phaseFlashSeconds;
        phaseTwoWasActive = isPhaseTwo;

        hitFlashRemaining = Mathf.Max(0f, hitFlashRemaining - dt);
        phaseFlashRemaining = Mathf.Max(0f, phaseFlashRemaining - dt);
        UpdateSpritesAndScale();
    }

    private static float SmoothTo(float current, float target, float smoothTime, float dt)
    {
        float factor = 1f - Mathf.Exp(-dt * 4.6f / Mathf.Max(0.02f, smoothTime));
        return Mathf.Lerp(current, target, factor);
    }

    private bool IsPhaseTwo()
    {
        return graveWardenAI != null && graveWardenAI.IsPhaseTwo;
    }

    private void HandleHealthChanged(float current, float maximum)
    {
        float next = maximum <= 0f ? 0f : Mathf.Clamp01(current / maximum);
        if (next + 0.0001f < targetRatio)
        {
            hitFlashRemaining = hurtFlashSeconds;
            trailResumeTime = Time.time + trailWaitSeconds;
        }
        else if (next > targetRatio)
        {
            // Healing shouldn't produce a delayed gold gap.
            trailRatio = Mathf.Max(trailRatio, next);
        }
        targetRatio = next;
    }

    private void HandleDeath()
    {
        targetRatio = 0f;
        if (hideImmediatelyOnDeath && barRoot != null)
            barRoot.gameObject.SetActive(false);
    }

    private void UpdateSpritesAndScale()
    {
        if (hpFill == null || damageTrail == null) return;
        if (normalHpSprite != null && phase2HpSprite != null)
            hpFill.sprite = IsPhaseTwo() ? phase2HpSprite : normalHpSprite;

        var frontScale = hpFill.transform.localScale;
        frontScale.x = Mathf.Clamp01(frontRatio);
        hpFill.transform.localScale = frontScale;

        var lagScale = damageTrail.transform.localScale;
        lagScale.x = Mathf.Clamp01(Mathf.Max(frontRatio, trailRatio));
        damageTrail.transform.localScale = lagScale;

        float hurtAmount = hurtFlashSeconds > 0f ? hitFlashRemaining / hurtFlashSeconds : 0f;
        float phaseAmount = phaseFlashSeconds > 0f ? phaseFlashRemaining / phaseFlashSeconds : 0f;
        hpFill.color = Color.Lerp(new Color(0.96f, 0.91f, 1f, 1f), Color.white, Mathf.Clamp01(hurtAmount * 0.75f));
        if (ornateBorder != null)
        {
            var baseTint = IsPhaseTwo() ? new Color(1f, 0.88f, 1f, 1f) : Color.white;
            ornateBorder.color = Color.Lerp(baseTint, new Color(0.92f, 0.78f, 1f, 1f), Mathf.Clamp01(phaseAmount * 0.75f));
        }
    }

    private void OnDisable()
    {
        if (health != null)
        {
            health.OnHealthChanged -= HandleHealthChanged;
            health.OnDied -= HandleDeath;
        }
    }
}
